SHOW WAREHOUSES LIKE 'WH_INMOBILIARIA';
SHOW SCHEMAS IN DATABASE INMOBILIARIA_DW;
SHOW GRANTS TO ROLE INMOBILIARIA_DATAOPS_LOADER;



